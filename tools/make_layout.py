#!/usr/bin/env python3
"""Turn the JSON files written by map/blender/osijek_export_gta.py into fivem-resources/osrp_osijek/layout.lua.

usage: python3 tools/make_layout.py <export dir> <layout.lua>
"""
import json
import os
import sys


def num(v):
    return f"{float(v):.2f}"


def val(v):
    if v is None:
        return "false"
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return num(v)
    if isinstance(v, list):
        return "{ " + ", ".join(val(x) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {val(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def block(name, rows, indent=""):
    out = [f"{indent}{name} = {{"]
    out += [f"{indent}    {val(r)}," for r in rows]
    out.append(f"{indent}}}" + ("," if indent else ""))
    return out


def main(src, dst):
    load = lambda n: json.load(open(os.path.join(src, f"osijek_{n}.json"), encoding="utf-8"))
    layout = load("layout")
    trees = [{"x": t["x"], "y": t["y"], "z": t.get("z", 0.14), "kind": t["kind"]} for t in load("trees")]
    lines = ["-- generated by map/blender/osijek_export_gta.py + tools/make_layout.py (positions relative to Config.Origin)"]
    lines += ["Layout = {"] + [f"    {{ name = '{c['name']}', x = {float(c['x']):.1f}, y = {float(c['y']):.1f}, z = {float(c['z']):.1f} }}," for c in layout] + ["}", ""]
    lines += block("Trees", trees) + [""]
    lines += block("Doors", load("doors")) + [""]
    lines += block("Furniture", load("furniture")) + [""]
    life = load("life")
    lines.append("Life = {")
    for k, rows in life.items():
        if isinstance(rows, dict):
            lines += [f"    {k} = {{"] + [f"        {n} = {val(v)}," for n, v in rows.items()] + ["    },"]
        else:
            lines += block(k, rows, "    ")
    lines.append("}")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"layout.lua: {len(layout)} chunks, {len(trees)} trees, " + ", ".join(f"{len(v)} {k.lower()}" for k, v in life.items()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
